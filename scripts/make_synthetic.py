def busy_dates(rng: random.Random) -> str:
    """Sample ~40% per autumn month and ~75% in December per profile.

    December weekends are reserved first, then weekdays fill the quota.
    September's quota applies only to the known calendar from September 23.
    """
    days = [START + timedelta(days=i) for i in range((END - START).days + 1)]
    busy = []
    for month in range(9, 13):
        available = [day for day in days if day.month == month]
        quota = round(len(available) * (0.75 if month == 12 else 0.4))
        weekends = [day for day in available if day.weekday() >= 5] if month == 12 else []
        choices = [day for day in available if day not in weekends]
        busy.extend(weekends + rng.sample(choices, quota - len(weekends)))
    return "|".join(day.isoformat() for day in sorted(busy))


def generate(output: Path = OUTPUT) -> None:
    with SOURCE.open(encoding="utf-8", newline="") as stream:
        fields = next(csv.reader(stream))
    rng = random.Random(79)
    with output.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        for index, profile in enumerate(PROFILES, 1):
            name, categories, city, price, formats, languages, hours, description = profile
            writer.writerow({
                "id": f"SYN-{index:05d}", "anon_name": name,
                "categories": categories, "city": city, "city_imputed": "False",
                "synthetic": "True", "price_from_kzt": price, "price_imputed": "False",
                "event_formats": formats, "languages": languages,
                "max_hours": "" if hours is None else hours,
                "busy_dates": busy_dates(rng), "description": description,
            })


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    generate(args.output)
    print(f"Wrote {len(PROFILES)} synthetic profiles to {args.output}")


if __name__ == "__main__":
    main()
